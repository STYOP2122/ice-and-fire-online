const { chromium } = require('playwright');
const fs = require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-webgl']});
 const context=await browser.newContext({viewport:{width:800,height:600}});
 const p=await context.newPage();const errors=[];
 p.on('pageerror',e=>errors.push(e.message));p.on('response',r=>{if(r.status()>=400)errors.push(r.status()+' '+r.url());});
 await p.goto('http://127.0.0.1:8080/games/1-forest-temple/');
 await p.waitForTimeout(10000);await p.screenshot({path:'test-results/game.png'});
 console.log('CANVAS',await p.locator('canvas').count(),'ERRORS',errors);
 await p.locator('#room-create').click();await p.waitForFunction(()=>document.querySelector('#room-copy').hidden===false,{timeout:30000});
 const id=await p.locator('#room-id').inputValue();console.log('ROOM',id);
 const guestContext=await browser.newContext({viewport:{width:844,height:390},isMobile:true,hasTouch:true});const g=await guestContext.newPage();
 await g.goto('http://127.0.0.1:8080/games/1-forest-temple/',{waitUntil:'domcontentloaded',timeout:90000});await g.waitForTimeout(5000);
 await g.locator('#room-id').fill(id);await g.locator('#room-join').click();
 await g.waitForFunction(()=>{let v=document.querySelector('video');return v&&v.videoWidth>0;},null,{timeout:40000});
 await g.screenshot({path:'test-results/mobile-room.png'});
 console.log('VIDEO',await g.locator('video').evaluate(v=>({w:v.videoWidth,h:v.videoHeight,time:v.currentTime})));
 await p.evaluate(()=>{window.received=[];window.addEventListener('keydown',e=>{if(e.roomRemote)window.received.push(e.keyCode);});});
 await g.locator('[data-key="68"]').dispatchEvent('touchstart');await g.waitForTimeout(400);await g.locator('[data-key="68"]').dispatchEvent('touchend');
 console.log('REMOTE_KEYS',await p.evaluate(()=>window.received));
 await g.locator('#room-leave').click();await p.waitForTimeout(1000);console.log('LEAVE',await p.locator('#room-status').textContent());
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
